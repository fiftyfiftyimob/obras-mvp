-- Canal do operario: modelo compartilhado pelo WhatsApp agora e pelo app no futuro.
create table public.canais_operario (
  id bigint generated by default as identity primary key,
  obra_id integer not null references public.obras(id) on delete cascade,
  colaborador_id integer not null references public.colaboradores(id) on delete cascade,
  tipo text not null default 'whatsapp' check (tipo in ('whatsapp', 'flutter')),
  telefone_e164 text not null check (telefone_e164 ~ '^\+[1-9][0-9]{7,14}$'),
  status text not null default 'pendente' check (status in ('pendente', 'ativo', 'bloqueado', 'inativo')),
  codigo_ativacao_hash text,
  codigo_expira_em timestamptz,
  tentativas_ativacao smallint not null default 0 check (tentativas_ativacao between 0 and 5),
  ativado_em timestamptz,
  ultimo_contato_em timestamptz,
  criado_por uuid not null references auth.users(id),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  unique (colaborador_id, tipo)
);

create index canais_operario_obra_idx on public.canais_operario(obra_id);
create unique index canais_operario_whatsapp_telefone_idx
  on public.canais_operario(telefone_e164)
  where tipo = 'whatsapp' and status <> 'inativo';

create table public.sessoes_operario (
  canal_id bigint primary key references public.canais_operario(id) on delete cascade,
  tarefa_ativa_id integer references public.tarefas(id) on delete set null,
  estado text not null default 'menu',
  dados jsonb not null default '{}'::jsonb,
  atualizado_em timestamptz not null default now()
);

create table public.whatsapp_outbox (
  id bigint generated by default as identity primary key,
  canal_id bigint not null references public.canais_operario(id) on delete cascade,
  telefone_e164 text not null,
  tipo text not null default 'texto' check (tipo in ('texto', 'imagem')),
  corpo text not null,
  metadados jsonb not null default '{}'::jsonb,
  status text not null default 'pendente' check (status in ('pendente', 'processando', 'enviado', 'erro')),
  tentativas smallint not null default 0 check (tentativas >= 0),
  disponivel_em timestamptz not null default now(),
  processando_em timestamptz,
  enviado_em timestamptz,
  provider_id text,
  ultimo_erro text,
  criado_em timestamptz not null default now()
);

create index whatsapp_outbox_pendente_idx
  on public.whatsapp_outbox(disponivel_em, id)
  where status in ('pendente', 'processando');

create table public.whatsapp_inbox (
  provider_id text primary key,
  canal_id bigint references public.canais_operario(id) on delete set null,
  telefone_e164 text not null,
  tipo text not null,
  corpo text,
  possui_midia boolean not null default false,
  metadados jsonb not null default '{}'::jsonb,
  status text not null default 'recebido' check (status in ('recebido', 'processado', 'ignorado', 'erro')),
  erro text,
  recebido_em timestamptz not null default now(),
  processado_em timestamptz
);

create table public.evidencias_tarefa (
  id bigint generated by default as identity primary key,
  tarefa_id integer not null references public.tarefas(id) on delete cascade,
  colaborador_id integer not null references public.colaboradores(id),
  canal_id bigint references public.canais_operario(id) on delete set null,
  inbox_provider_id text unique references public.whatsapp_inbox(provider_id),
  tipo text not null default 'foto' check (tipo in ('foto', 'documento')),
  storage_path text not null unique,
  mime_type text not null,
  legenda text,
  criado_em timestamptz not null default now()
);

create index evidencias_tarefa_tarefa_idx on public.evidencias_tarefa(tarefa_id, criado_em);

