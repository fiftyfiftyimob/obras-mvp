create or replace function private.registrar_evolucao(
  p_tarefa integer,
  p_tipo text,
  p_quantidade numeric,
  p_motivo text,
  p_observacao text
) returns integer
language plpgsql security definer set search_path = '' as $$
declare tarefa public.tarefas; novo_status text; evento integer;
begin
 select t.* into tarefa
 from public.tarefas t
 join public.obras o on o.id=t.obra_id
 where t.id=p_tarefa and o.dono_id=auth.uid() and o.ativo
 for update of t;
 if not found then raise exception 'Tarefa nao encontrada.'; end if;
 if p_quantidade is null or p_quantidade<0 then raise exception 'Quantidade invalida.'; end if;
 if p_tipo='inicio' and tarefa.status='nao_iniciada' then novo_status:='em_execucao';
 elsif p_tipo='pausa' and tarefa.status='em_execucao' then novo_status:='pausada';
 elsif p_tipo='retomada' and tarefa.status in ('pausada','bloqueada','aguardando_validacao') then novo_status:='em_execucao';
 elsif p_tipo='conclusao' and tarefa.status in ('em_execucao','aguardando_validacao') then novo_status:='concluida';
 elsif p_tipo='impedimento' and tarefa.status in ('nao_iniciada','em_execucao','pausada') then novo_status:='bloqueada';
 elsif p_tipo='producao' and tarefa.status='em_execucao' then novo_status:=tarefa.status;
 else raise exception 'Esta acao nao e permitida no estado atual da tarefa.'; end if;
 if p_tipo='impedimento' and (p_motivo is null or p_motivo not in ('falta_material','falta_ferramenta','frente_ocupada','projeto_pendente','chuva','espera_equipe','seguranca','outro')) then raise exception 'Informe o motivo do impedimento.'; end if;
 if p_tipo in ('inicio','retomada') and p_quantidade<>0 then raise exception 'Registre producao ao pausar, concluir ou informar impedimento.'; end if;
 if p_tipo='producao' and p_quantidade<=0 then raise exception 'Informe uma quantidade maior que zero.'; end if;
 insert into public.evolucoes_tarefa(tarefa_id,autor_id,tipo,quantidade_realizada,motivo_impedimento,observacao)
 values(p_tarefa,auth.uid(),p_tipo,p_quantidade,case when p_tipo='impedimento' then p_motivo else null end,p_observacao)
 returning id into evento;
 update public.tarefas set status=novo_status,atualizado_em=now() where id=p_tarefa;
 return evento;
end $$;

create or replace function private.normalizar_telefone(p_telefone text) returns text
language plpgsql immutable security invoker set search_path = '' as $$
declare digitos text := regexp_replace(coalesce(p_telefone,''), '[^0-9]', '', 'g');
begin
  if length(digitos) in (10,11) then digitos := '55' || digitos; end if;
  if length(digitos) < 10 or length(digitos) > 15 then
    raise exception 'Telefone invalido. Informe DDD e numero.';
  end if;
  return '+' || digitos;
end $$;

create function private.tarefa_atribuida(p_canal bigint, p_tarefa integer) returns boolean
language sql stable security invoker set search_path = '' as $$
  select exists (
    select 1
    from public.canais_operario c
    join public.tarefas t on t.id = p_tarefa and t.obra_id = c.obra_id
    where c.id = p_canal and c.status = 'ativo' and c.tipo = 'whatsapp'
      and (
        t.colaborador_id = c.colaborador_id
        or exists (
          select 1 from public.equipe_colaboradores ec
          where ec.equipe_id = t.equipe_id
            and ec.colaborador_id = c.colaborador_id
            and ec.ativo
            and t.data >= ec.data_inicio
            and (ec.data_fim is null or t.data <= ec.data_fim)
        )
      )
  );
$$;

create function public.emitir_acesso_operario(p_colaborador integer)
returns table(canal_id bigint, codigo text, telefone_e164 text, expira_em timestamptz)
language plpgsql security definer set search_path = '' as $$
declare c public.colaboradores; v_codigo text; v_canal bigint; v_telefone text; v_expira timestamptz;
begin
  select col.* into c
  from public.colaboradores col
  join public.obras o on o.id=col.obra_id
  where col.id=p_colaborador and col.ativo and o.ativo and o.dono_id=auth.uid();
  if not found then raise exception 'Colaborador nao encontrado.'; end if;
  v_telefone := private.normalizar_telefone(c.telefone);
  v_codigo := lpad((floor(random()*1000000))::integer::text, 6, '0');
  v_expira := now() + interval '24 hours';

  insert into public.canais_operario(
    obra_id,colaborador_id,tipo,telefone_e164,status,codigo_ativacao_hash,
    codigo_expira_em,tentativas_ativacao,ativado_em,criado_por,atualizado_em
  ) values (
    c.obra_id,c.id,'whatsapp',v_telefone,'pendente',
    encode(extensions.digest(v_codigo,'sha256'),'hex'),v_expira,0,null,auth.uid(),now()
  )
  on conflict (colaborador_id,tipo) do update set
    telefone_e164=excluded.telefone_e164,status='pendente',
    codigo_ativacao_hash=excluded.codigo_ativacao_hash,codigo_expira_em=excluded.codigo_expira_em,
    tentativas_ativacao=0,ativado_em=null,criado_por=auth.uid(),atualizado_em=now()
  returning id into v_canal;

  insert into public.sessoes_operario(canal_id) values(v_canal)
  on conflict (canal_id) do update set tarefa_ativa_id=null,estado='menu',dados='{}',atualizado_em=now();

  insert into public.whatsapp_outbox(canal_id,telefone_e164,corpo)
  values(
    v_canal,v_telefone,
    format('Ola, %s! Voce recebeu acesso ao acompanhamento da obra. Responda *ATIVAR %s* em ate 24 horas. Se nao reconhece esta mensagem, ignore.', c.nome, v_codigo)
  );
  return query select v_canal,v_codigo,v_telefone,v_expira;
end $$;

revoke all on function public.emitir_acesso_operario(integer) from public,anon;
grant execute on function public.emitir_acesso_operario(integer) to authenticated;

