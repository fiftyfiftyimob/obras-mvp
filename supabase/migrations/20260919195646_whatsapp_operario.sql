create function public.registrar_whatsapp_inbox(
  p_provider_id text,p_telefone text,p_tipo text,p_corpo text,
  p_possui_midia boolean default false,p_metadados jsonb default '{}'::jsonb
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_phone text; v_canal public.canais_operario; inseriu integer;
begin
  v_phone := private.normalizar_telefone(p_telefone);
  select * into v_canal from public.canais_operario
  where tipo='whatsapp' and telefone_e164=v_phone and status<>'inativo'
  order by id desc limit 1;
  insert into public.whatsapp_inbox(provider_id,canal_id,telefone_e164,tipo,corpo,possui_midia,metadados)
  values(p_provider_id,v_canal.id,v_phone,p_tipo,p_corpo,p_possui_midia,coalesce(p_metadados,'{}'::jsonb))
  on conflict (provider_id) do nothing;
  get diagnostics inseriu = row_count;
  if inseriu=0 then return jsonb_build_object('aceita',false); end if;
  if v_canal.id is not null then
    update public.canais_operario set ultimo_contato_em=now(),atualizado_em=now() where id=v_canal.id;
  end if;
  return jsonb_build_object('aceita',true,'canal_id',v_canal.id,'status',v_canal.status);
end $$;

create function public.ativar_canal_whatsapp(p_telefone text,p_codigo text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_phone text; c public.canais_operario;
begin
  v_phone := private.normalizar_telefone(p_telefone);
  select * into c from public.canais_operario
  where tipo='whatsapp' and telefone_e164=v_phone and status='pendente'
  order by id desc limit 1 for update;
  if not found then raise exception 'Nenhum acesso pendente para este telefone.'; end if;
  if c.codigo_expira_em < now() then
    return jsonb_build_object('ativado',false,'erro','Codigo expirado. Solicite um novo acesso ao gestor.');
  end if;
  if c.tentativas_ativacao >= 5 then
    return jsonb_build_object('ativado',false,'erro','Acesso bloqueado. Solicite um novo codigo ao gestor.');
  end if;
  if c.codigo_ativacao_hash <> encode(extensions.digest(trim(p_codigo),'sha256'),'hex') then
    update public.canais_operario set tentativas_ativacao=tentativas_ativacao+1,
      status=case when tentativas_ativacao+1>=5 then 'bloqueado' else status end,
      atualizado_em=now() where id=c.id;
    return jsonb_build_object('ativado',false,'erro','Codigo invalido.');
  end if;
  update public.canais_operario set status='ativo',codigo_ativacao_hash=null,
    codigo_expira_em=null,tentativas_ativacao=0,ativado_em=now(),atualizado_em=now()
  where id=c.id;
  insert into public.sessoes_operario(canal_id) values(c.id) on conflict do nothing;
  return jsonb_build_object('ativado',true,'canal_id',c.id,'colaborador_id',c.colaborador_id,'obra_id',c.obra_id);
end $$;

create function public.listar_tarefas_whatsapp(p_canal bigint) returns jsonb
language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_agg(to_jsonb(x) order by x.data,x.id),'[]'::jsonb)
  from (
    select t.id,t.data,t.turno,t.quantidade_meta,t.unidade,t.status,
      s.nome servico,f.nome frente
    from public.tarefas t
    join public.servicos s on s.id=t.servico_id
    join public.frentes f on f.id=t.frente_id
    where private.tarefa_atribuida(p_canal,t.id)
      and t.status <> 'concluida'
      and t.data between current_date-interval '7 days' and current_date+interval '14 days'
  ) x;
$$;

create function public.registrar_evolucao_operario(
  p_canal bigint,p_tarefa integer,p_tipo text,p_quantidade numeric default 0,
  p_motivo text default null,p_observacao text default null
) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare c public.canais_operario; t public.tarefas; v_tipo text; v_status text; v_evento integer;
begin
  if not private.tarefa_atribuida(p_canal,p_tarefa) then raise exception 'Tarefa nao atribuida a este colaborador.'; end if;
  select * into c from public.canais_operario where id=p_canal and status='ativo';
  select * into t from public.tarefas where id=p_tarefa for update;
  if p_quantidade is null or p_quantidade<0 then raise exception 'Quantidade invalida.'; end if;
  if p_tipo='inicio' and t.status='nao_iniciada' then v_tipo:='inicio'; v_status:='em_execucao';
  elsif p_tipo='pausa' and t.status='em_execucao' then v_tipo:='pausa'; v_status:='pausada';
  elsif p_tipo='retomada' and t.status in ('pausada','bloqueada') then v_tipo:='retomada'; v_status:='em_execucao';
  elsif p_tipo='producao' and t.status='em_execucao' and p_quantidade>0 then v_tipo:='producao'; v_status:=t.status;
  elsif p_tipo='conclusao' and t.status='em_execucao' then v_tipo:='solicitacao_conclusao'; v_status:='aguardando_validacao';
  elsif p_tipo='impedimento' and t.status in ('nao_iniciada','em_execucao','pausada') then v_tipo:='impedimento'; v_status:='bloqueada';
  else raise exception 'Esta acao nao e permitida no estado atual da tarefa.'; end if;
  if p_tipo='impedimento' and coalesce(p_motivo,'') not in ('falta_material','falta_ferramenta','frente_ocupada','projeto_pendente','chuva','espera_equipe','seguranca','outro') then raise exception 'Informe um motivo valido.'; end if;
  if p_tipo in ('inicio','retomada') and p_quantidade<>0 then raise exception 'Quantidade nao permitida nesta acao.'; end if;
  insert into public.evolucoes_tarefa(tarefa_id,colaborador_id,tipo,quantidade_realizada,motivo_impedimento,observacao)
  values(p_tarefa,c.colaborador_id,v_tipo,p_quantidade,case when p_tipo='impedimento' then p_motivo end,p_observacao)
  returning id into v_evento;
  update public.tarefas set status=v_status,atualizado_em=now() where id=p_tarefa;
  insert into public.sessoes_operario(canal_id,tarefa_ativa_id,estado,atualizado_em)
  values(p_canal,case when v_status='em_execucao' then p_tarefa else null end,'menu',now())
  on conflict (canal_id) do update set
    tarefa_ativa_id=excluded.tarefa_ativa_id,estado='menu',atualizado_em=now();
  return jsonb_build_object('evento_id',v_evento,'status',v_status,'tarefa_id',p_tarefa);
end $$;

create function public.obter_sessao_whatsapp(p_canal bigint) returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'canal_id',c.id,'obra_id',c.obra_id,'colaborador_id',c.colaborador_id,
    'status',c.status,'tarefa_ativa_id',s.tarefa_ativa_id
  ) from public.canais_operario c
  left join public.sessoes_operario s on s.canal_id=c.id
  where c.id=p_canal and c.tipo='whatsapp';
$$;

create function public.registrar_evidencia_whatsapp(
  p_canal bigint,p_tarefa integer,p_provider_id text,p_storage_path text,
  p_mime_type text,p_legenda text default null
) returns bigint
language plpgsql security definer set search_path = '' as $$
declare c public.canais_operario; v_id bigint;
begin
  if not private.tarefa_atribuida(p_canal,p_tarefa) then raise exception 'Tarefa nao atribuida a este colaborador.'; end if;
  select * into c from public.canais_operario where id=p_canal and status='ativo';
  if p_storage_path !~ ('^'||c.obra_id::text||'/'||p_tarefa::text||'/') then raise exception 'Caminho de arquivo invalido.'; end if;
  insert into public.evidencias_tarefa(tarefa_id,colaborador_id,canal_id,inbox_provider_id,storage_path,mime_type,legenda)
  values(p_tarefa,c.colaborador_id,p_canal,p_provider_id,p_storage_path,p_mime_type,p_legenda)
  returning id into v_id;
  return v_id;
end $$;

create function public.finalizar_whatsapp_inbox(p_provider_id text,p_status text,p_erro text default null) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if p_status not in ('processado','ignorado','erro') then raise exception 'Status invalido.'; end if;
  update public.whatsapp_inbox set status=p_status,erro=p_erro,processado_em=now()
  where provider_id=p_provider_id;
end $$;

create function public.claim_whatsapp_outbox(p_limite integer default 20)
returns table(id bigint,canal_id bigint,telefone_e164 text,tipo text,corpo text,metadados jsonb)
language plpgsql security definer set search_path = '' as $$
begin
  update public.whatsapp_outbox set status='pendente',processando_em=null
  where status='processando' and processando_em < now()-interval '5 minutes';
  return query
  with fila as (
    select o.id from public.whatsapp_outbox o
    where o.status='pendente' and o.disponivel_em<=now() and o.tentativas<5
    order by o.id for update skip locked limit greatest(1,least(p_limite,100))
  ), atualizada as (
    update public.whatsapp_outbox o set status='processando',processando_em=now(),tentativas=tentativas+1
    from fila where o.id=fila.id
    returning o.id,o.canal_id,o.telefone_e164,o.tipo,o.corpo,o.metadados
  ) select * from atualizada;
end $$;

create function public.finalizar_whatsapp_outbox(
  p_id bigint,p_enviado boolean,p_provider_id text default null,p_erro text default null
) returns void
language plpgsql security definer set search_path = '' as $$
begin
  update public.whatsapp_outbox set
    status=case when p_enviado then 'enviado' when tentativas>=5 then 'erro' else 'pendente' end,
    enviado_em=case when p_enviado then now() else enviado_em end,
    provider_id=case when p_enviado then p_provider_id else provider_id end,
    ultimo_erro=case when p_enviado then null else left(p_erro,1000) end,
    disponivel_em=case when p_enviado then disponivel_em else now() + (interval '30 seconds' * greatest(tentativas,1)) end,
    processando_em=null
  where id=p_id and status='processando';
end $$;

create function private.enfileirar_tarefa_whatsapp() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.whatsapp_outbox(canal_id,telefone_e164,corpo,metadados)
  select distinct c.id,c.telefone_e164,
    format(
      'Nova tarefa #%s\nData: %s%s\nServico: %s\nFrente: %s\nMeta: %s %s\n\nResponda *MENU* para ver os comandos.',
      new.id,to_char(new.data,'DD/MM/YYYY'),
      case when new.turno is null then '' else ' · '||new.turno end,
      sv.nome,f.nome,new.quantidade_meta,new.unidade
    ),
    jsonb_build_object('tarefa_id',new.id,'evento','nova_tarefa')
  from public.canais_operario c
  join public.servicos sv on sv.id=new.servico_id
  join public.frentes f on f.id=new.frente_id
  where c.obra_id=new.obra_id and c.tipo='whatsapp' and c.status='ativo'
    and (
      c.colaborador_id=new.colaborador_id
      or exists (
        select 1 from public.equipe_colaboradores ec
        where ec.equipe_id=new.equipe_id and ec.colaborador_id=c.colaborador_id
          and ec.ativo and new.data>=ec.data_inicio
          and (ec.data_fim is null or new.data<=ec.data_fim)
      )
    );
  return new;
end $$;

