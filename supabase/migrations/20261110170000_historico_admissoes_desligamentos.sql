alter table public.colaboradores
  add column if not exists data_admissao date;

create table if not exists public.colaborador_periodos (
  id bigint generated by default as identity primary key,
  obra_id integer not null references public.obras(id) on delete cascade,
  colaborador_id integer not null references public.colaboradores(id) on delete cascade,
  data_admissao date not null,
  data_desligamento date,
  motivo_desligamento text,
  origem text not null default 'registrada'
    check (origem in ('registrada', 'simulacao', 'vinculo_legado')),
  criado_em timestamptz not null default pg_catalog.now(),
  criado_por uuid,
  constraint colaborador_periodos_datas_validas
    check (data_desligamento is null or data_desligamento >= data_admissao),
  constraint colaborador_periodos_motivo
    check (motivo_desligamento is null or pg_catalog.length(motivo_desligamento) <= 1000)
);

create index if not exists colaborador_periodos_obra_datas_idx
  on public.colaborador_periodos (obra_id, data_admissao, data_desligamento);
create index if not exists colaborador_periodos_colaborador_datas_idx
  on public.colaborador_periodos (colaborador_id, data_admissao desc);
create unique index if not exists colaborador_periodos_um_vinculo_aberto_idx
  on public.colaborador_periodos (colaborador_id)
  where data_desligamento is null;

alter table public.colaborador_periodos enable row level security;
revoke all on public.colaborador_periodos from anon, authenticated;
grant select on public.colaborador_periodos to authenticated;
drop policy if exists colaborador_periodos_select_obra on public.colaborador_periodos;
create policy colaborador_periodos_select_obra
  on public.colaborador_periodos for select to authenticated
  using (private.possui_obra(obra_id));

create or replace function private.preparar_admissao_colaborador()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.data_admissao is null then
    new.data_admissao := (pg_catalog.now() at time zone 'America/Sao_Paulo')::date;
  end if;
  return new;
end;
$$;

create or replace function private.registrar_admissao_inicial_colaborador()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_equipe_obra_id integer;
  v_papel text;
begin
  if auth.uid() is null then
    raise exception 'Entre novamente para registrar a admissão.';
  end if;
  v_papel := private.papel_obra(new.obra_id);
  if v_papel is null or v_papel not in ('administrador', 'engenheiro', 'supervisor') then
    raise exception 'Seu perfil não pode registrar admissões nesta obra.';
  end if;

  insert into public.colaborador_periodos (
    obra_id, colaborador_id, data_admissao, criado_por
  )
  values (
    new.obra_id, new.id, new.data_admissao, auth.uid()
  );

  if new.equipe_principal_id is not null then
    select e.obra_id into v_equipe_obra_id
    from public.equipes e
    where e.id = new.equipe_principal_id
      and e.ativo;

    if v_equipe_obra_id is distinct from new.obra_id then
      raise exception 'A equipe principal precisa estar ativa na mesma obra.';
    end if;

    insert into public.equipe_colaboradores (
      equipe_id, colaborador_id, data_inicio, ativo
    )
    values (
      new.equipe_principal_id, new.id, new.data_admissao, true
    );
  end if;
  return new;
end;
$$;

drop trigger if exists preparar_admissao_colaborador on public.colaboradores;
create trigger preparar_admissao_colaborador
  before insert on public.colaboradores
  for each row execute function private.preparar_admissao_colaborador();

drop trigger if exists registrar_admissao_inicial_colaborador on public.colaboradores;
create trigger registrar_admissao_inicial_colaborador
  after insert on public.colaboradores
  for each row execute function private.registrar_admissao_inicial_colaborador();

revoke all on function private.preparar_admissao_colaborador() from public, anon, authenticated;
revoke all on function private.registrar_admissao_inicial_colaborador() from public, anon, authenticated;

-- Seed the fictional test work from its existing, date-stamped team history.
-- Original test staff began with the work; simulated hires and dismissals use their recorded team dates.
with target_work as (
  select id from public.obras
  where nome = 'Residencial Horizonte — Teste Operacional'
), employment_dates as (
  select c.id as colaborador_id, c.obra_id,
         min(ec.data_inicio) as data_admissao,
         case when not c.ativo and c.nome like 'SIMULACAO -%'
              then max(ec.data_fim) else null end as data_desligamento,
         case when c.nome like 'SIMULACAO -%' then 'simulacao' else 'vinculo_legado' end as origem
  from public.colaboradores c
  join target_work w on w.id = c.obra_id
  join public.equipe_colaboradores ec on ec.colaborador_id = c.id
  group by c.id, c.obra_id, c.ativo, c.nome
)
insert into public.colaborador_periodos (
  obra_id, colaborador_id, data_admissao, data_desligamento,
  motivo_desligamento, origem
)
select obra_id, colaborador_id, data_admissao, data_desligamento,
       case when data_desligamento is not null
            then 'Desligamento registrado na simulação anual.' end,
       origem
from employment_dates
where data_admissao is not null
on conflict do nothing;

update public.colaboradores c
set data_admissao = p.data_admissao
from public.colaborador_periodos p
where p.colaborador_id = c.id
  and c.obra_id = p.obra_id
  and p.origem in ('simulacao', 'vinculo_legado')
  and c.obra_id in (
    select id from public.obras
    where nome = 'Residencial Horizonte — Teste Operacional'
  )
  and c.data_admissao is null;

create or replace function public.registrar_desligamento_colaborador(
  p_colaborador_id integer,
  p_data_desligamento date,
  p_motivo_desligamento text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_obra_id integer;
  v_admissao date;
  v_papel text;
  v_hoje date := (pg_catalog.now() at time zone 'America/Sao_Paulo')::date;
  v_periodo_id bigint;
  v_tem_periodo boolean;
begin
  if auth.uid() is null then
    raise exception 'Entre novamente para registrar o desligamento.';
  end if;
  if p_colaborador_id is null or p_data_desligamento is null then
    raise exception 'Informe o colaborador e a data do desligamento.';
  end if;
  if p_motivo_desligamento is not null and pg_catalog.length(pg_catalog.btrim(p_motivo_desligamento)) > 1000 then
    raise exception 'O motivo pode ter até 1000 caracteres.';
  end if;

  select c.obra_id into v_obra_id
  from public.colaboradores c
  where c.id = p_colaborador_id
  for update;

  if not found then
    raise exception 'Colaborador não encontrado.';
  end if;
  v_papel := private.papel_obra(v_obra_id);
  if v_papel is null or v_papel not in ('administrador', 'engenheiro', 'supervisor') then
    raise exception 'Seu perfil não pode registrar admissões ou desligamentos nesta obra.';
  end if;

  select p.id, p.data_admissao into v_periodo_id, v_admissao
  from public.colaborador_periodos p
  where p.colaborador_id = p_colaborador_id
    and p.obra_id = v_obra_id
    and p.data_admissao <= p_data_desligamento
    and (p.data_desligamento is null or p.data_desligamento >= p_data_desligamento)
  order by p.data_admissao desc, p.id desc
  limit 1
  for update;
  v_tem_periodo := found;

  if not v_tem_periodo then
    select c.data_admissao into v_admissao
    from public.colaboradores c
    where c.id = p_colaborador_id;
    if v_admissao is null then
      select pg_catalog.min(ec.data_inicio) into v_admissao
      from public.equipe_colaboradores ec
      where ec.colaborador_id = p_colaborador_id;
    end if;
    v_admissao := coalesce(v_admissao, p_data_desligamento);
    if p_data_desligamento < v_admissao then
      raise exception 'A data de desligamento não pode ser anterior ao início do histórico conhecido.';
    end if;
    insert into public.colaborador_periodos (
      obra_id, colaborador_id, data_admissao, data_desligamento,
      motivo_desligamento, origem, criado_por
    )
    values (
      v_obra_id, p_colaborador_id, v_admissao, p_data_desligamento,
      nullif(pg_catalog.btrim(p_motivo_desligamento), ''), 'vinculo_legado', auth.uid()
    )
    returning id into v_periodo_id;
  else
    if p_data_desligamento < v_admissao then
      raise exception 'A data de desligamento não pode ser anterior à admissão.';
    end if;
    update public.colaborador_periodos
    set data_desligamento = p_data_desligamento,
        motivo_desligamento = nullif(pg_catalog.btrim(p_motivo_desligamento), '')
    where id = v_periodo_id;
  end if;

  if exists (
    select 1 from public.equipe_colaboradores ec
    where ec.colaborador_id = p_colaborador_id
      and ec.ativo and ec.data_inicio > p_data_desligamento
  ) then
    raise exception 'Encerre ou ajuste primeiro os vínculos de equipe agendados após essa data.';
  end if;

  update public.equipe_colaboradores
  set data_fim = p_data_desligamento,
      ativo = p_data_desligamento >= v_hoje
  where colaborador_id = p_colaborador_id
    and ativo
    and data_inicio <= p_data_desligamento
    and (data_fim is null or data_fim >= p_data_desligamento);

  update public.colaboradores
  set ativo = p_data_desligamento >= v_hoje
  where id = p_colaborador_id and obra_id = v_obra_id;

  return v_periodo_id;
end;
$$;

create or replace function public.registrar_admissao_colaborador(
  p_colaborador_id integer,
  p_data_admissao date,
  p_equipe_id integer default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_obra_id integer;
  v_equipe_obra_id integer;
  v_papel text;
  v_hoje date := (pg_catalog.now() at time zone 'America/Sao_Paulo')::date;
  v_periodo_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Entre novamente para registrar a admissão.';
  end if;
  if p_colaborador_id is null or p_data_admissao is null then
    raise exception 'Informe o colaborador e a data da admissão.';
  end if;

  select c.obra_id into v_obra_id
  from public.colaboradores c
  where c.id = p_colaborador_id
  for update;

  if not found then
    raise exception 'Colaborador não encontrado.';
  end if;
  v_papel := private.papel_obra(v_obra_id);
  if v_papel is null or v_papel not in ('administrador', 'engenheiro', 'supervisor') then
    raise exception 'Seu perfil não pode registrar admissões ou desligamentos nesta obra.';
  end if;

  if exists (
    select 1 from public.colaborador_periodos p
    where p.colaborador_id = p_colaborador_id
      and p.obra_id = v_obra_id
      and p.data_admissao <= coalesce(p_data_admissao, 'infinity'::date)
      and coalesce(p.data_desligamento, 'infinity'::date) >= p_data_admissao
  ) then
    raise exception 'Já existe um vínculo de trabalho que cobre essa data.';
  end if;

  if p_equipe_id is not null then
    select e.obra_id into v_equipe_obra_id
    from public.equipes e
    where e.id = p_equipe_id and e.ativo
    for update;
    if not found or v_equipe_obra_id is distinct from v_obra_id then
      raise exception 'A equipe precisa estar ativa na mesma obra.';
    end if;
  end if;

  insert into public.colaborador_periodos (
    obra_id, colaborador_id, data_admissao, origem, criado_por
  )
  values (
    v_obra_id, p_colaborador_id, p_data_admissao, 'registrada', auth.uid()
  )
  returning id into v_periodo_id;

  update public.colaboradores c
  set ativo = true,
      equipe_principal_id = case
        when p_equipe_id is not null and p_data_admissao <= v_hoje then p_equipe_id
        else c.equipe_principal_id
      end
  where c.id = p_colaborador_id and c.obra_id = v_obra_id;

  if p_equipe_id is not null then
    insert into public.equipe_colaboradores (
      equipe_id, colaborador_id, data_inicio, ativo
    )
    values (p_equipe_id, p_colaborador_id, p_data_admissao, true);
  end if;

  return v_periodo_id;
end;
$$;

revoke all on function public.registrar_desligamento_colaborador(integer, date, text) from public, anon;
revoke all on function public.registrar_admissao_colaborador(integer, date, integer) from public, anon;
grant execute on function public.registrar_desligamento_colaborador(integer, date, text) to authenticated;
grant execute on function public.registrar_admissao_colaborador(integer, date, integer) to authenticated;